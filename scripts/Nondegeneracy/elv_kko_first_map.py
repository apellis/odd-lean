#!/usr/bin/env python3
"""First-strand KKO P compatibility with an even exterior deformation.

Exact identities in the free two-strand odd nilHecke/Ore models. f=x²-xd
is ELV degree two with top even coefficient zero. Tests the proposed source
right-dot twist and checks one KKO intertwiner identity modulo a LEFT ideal.
This is not the all-rank projectivity theorem.
"""
import sympy as s
from cyclotomic_score_audit import Reducer


def run():
    for mixed in (False,True):
        r=Reducer(mixed)
        def p(w):return r.polynomial([(1,tuple(w))])
        def add(*ps):
            return r.polynomial((c,w) for a in ps for w,c in a.items())
        def neg(a):return {w:-c for w,c in a.items()}
        def mul(a,b):
            return r.polynomial((c*d,u+v) for u,c in a.items() for v,d in b.items())
        X,Y,D,T=map(p,("x","y","d","t"))
        F=add(p("xx"),neg(p("xd")))
        H=neg(add(X,D,D)) # beta has one odd strand; inverse twist +2d
        residual=add(mul(mul(H,F),T),neg(mul(mul(F,T),Y)))
        assert residual==({} if mixed else neg(F))
        old=add(mul(mul(neg(X),F),T),neg(mul(mul(F,T),Y)))
        assert old!=residual
        if mixed:
            # The old j cyclotomic relation in the source lands in the
            # target LEFT ideal generated by f_j(x); e is independent of d.
            FJY=add(p("yy"),neg(p("ye")))
            FJX=add(p("xx"),neg(p("xe")))
            assert mul(mul(FJY,F),T)==mul(mul(F,T),FJX)
        if not mixed:
            delta=add(p("yy"),neg(p("xx")))
            G=add(mul(delta,add(Y,neg(X))),neg(mul(mul(delta,delta),T)))
            FY=add(p("yy"),neg(p("yd")))
            diff=add(mul(mul(G,F),T),neg(mul(FY,mul(add(X,neg(Y)),add(X,neg(Y))))))
            # Test membership in R_2*f, the left ideal defining K0 at beta=i,
            # rather than incorrectly reducing by the full two-sided ideal.
            candidates=[]
            for e in (0,1):
                for t in (0,1):
                    for a in range(5):
                        b=2+t-e-a
                        if b>=0:
                            w="d"*e+"x"*a+"y"*b+"t"*t
                            candidates.append((w,mul(p(w),F)))
            keys=sorted(set(diff).union(*(set(q) for _,q in candidates)))
            mat=s.Matrix([[q.get(w,0) for _,q in candidates] for w in keys])
            rhs=s.Matrix([diff.get(w,0) for w in keys])
            solution=mat.gauss_jordan_solve(rhs)[0]
            params=set().union(*(v.free_symbols for v in solution))
            solution=solution.subs({v:0 for v in params})
            assert mat*solution==rhs
            witness=[(w,int(c)) for (w,_),c in zip(candidates,solution) if c]
            print("PASS same-colour KKO8.18 local left-ideal witness:",witness)
        print(f"PASS {'mixed' if mixed else 'same-colour'} P right-dot twist; original-action control")
    print("SCOPE: first-map algebra identities, no all-rank projectivity/action")


if __name__ == "__main__":
    run()
